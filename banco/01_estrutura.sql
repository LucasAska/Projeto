SET NAMES utf8mb4;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS PEDIDOS_ITENS;
DROP TABLE IF EXISTS PEDIDOS;
DROP TABLE IF EXISTS PRODUTOS;
DROP TABLE IF EXISTS CATEGORIAS;
DROP TABLE IF EXISTS USUARIOS;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE USUARIOS(
    id INT AUTO_INCREMENT PRIMARY KEY,

    NOME VARCHAR(100) NOT NULL,
    TELEFONE VARCHAR(20) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL UNIQUE,
    SENHA VARCHAR(255) NOT NULL,
    
    -- endereço
    CEP VARCHAR(9) NOT NULL,
    LOGRADOURO VARCHAR(255) NOT NULL,
    NUMERO VARCHAR(20) NOT NULL,
    COMPLEMENTO VARCHAR(100) DEFAULT NULL,
    BAIRRO VARCHAR(100) NOT NULL,
    CIDADE VARCHAR(100) NOT NULL,
    UF CHAR(2) NOT NULL,

    -- Tipo de usuario criado / foi setado cliente como inicial
    TIPO ENUM('cliente', 'admin') NOT NULL DEFAULT 'cliente',
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Criou a categoria da qual os produtos vão se ingressar
CREATE TABLE CATEGORIAS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(70) NOT NULL,
    -- Slug é o nome de forma simples para poder ser utilizado em filtros e urls por isso tem que se unico
    SLUG VARCHAR(70) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE PRODUTOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    CATEGORIA_ID INT NOT NULL,
    NOME VARCHAR(150) NOT NULL,
    DESCRICAO TEXT(255),
    PRECO DECIMAL(10,2) NOT NULL,
    ESTOQUE INT NOT NULL DEFAULT 0,
    IMAGEM VARCHAR(255) DEFAULT NULL,
    ATIVO TINYINT(1) NOT NULL DEFAULT 1,
    CRIADO_EM  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_prod_preco CHECK(PRECO >= 0),
    CONSTRAINT ck_prod_estoque CHECK(ESTOQUE >= 0),

    CONSTRAINT fk_prod_cat FOREIGN KEY (CATEGORIA_ID)
        REFERENCES CATEGORIAS(ID) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Tabela de pedidos aqui é onde os pedidos são armazenados
CREATE TABLE PEDIDOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,

    -- FK que puxa o nome o usuario para o pedido
    USUARIO_ID INT NOT NULL,

    -- Status do pedido
    STATUS ENUM('pendente', 'atendido', 'cancelado') NOT NULL DEFAULT 'pendente',
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

 
    CONSTRAINT fk_pedi_usua FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIOS(ID) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Tabela de pedido_itens é onde os pedidos são relacionados a os itens
CREATE TABLE PEDIDOS_ITENS (
    ID INT AUTO_INCREMENT PRIMARY KEY,

    -- FK que conecta com pedidos
    PEDIDO_ID INT NOT NULL,
    -- FK que conecta com produtos
    PRODUTO_ID INT NOT NULL,

    QUANTIDADE INT NOT NULL,

    PRECO_UNIT DECIMAL(10,2) NOT NULL,

    CONSTRAINT fk_pedi_iten FOREIGN KEY (PEDIDO_ID)
        REFERENCES PEDIDOS(ID) ON DELETE CASCADE,

    CONSTRAINT fk_prod_iten FOREIGN KEY (PRODUTO_ID)
        REFERENCES PRODUTOS(ID),

    CONSTRAINT ck_item_quant CHECK(QUANTIDADE >= 1),

    CONSTRAINT ck_item_preco CHECK(PRECO_UNIT >= 0)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;